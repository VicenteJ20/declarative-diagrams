import { useEffect, useMemo, useRef } from "react";
import { attach } from "@dgm/core/runtime";
import { applyPalette, isMode, resolveTheme, themeToCssVars } from "@dgm/core/themes";
import type { Mode, Palette, ThemeDef, ResolvedTheme } from "@dgm/core/themes";

export interface DiagramProps {
  /** SVG string produced by the Vite plugin (`import svg from "./x.diagram.yaml"`) or `renderSvg()`. */
  svg: string;
  caption?: string;
  /**
   * `auto` (default): follow the site (`<html data-theme="dark">` / `.dark`) and fall back to the OS setting.
   * `light` / `dark`: force it.
   */
  mode?: Mode;
  /**
   * Colour theme: a built-in name ("olive", "azure", "aws"…) or an imported `*.theme.yaml` object.
   * Applied at runtime through CSS variables, so it can change without rebuilding.
   * Legacy: "light" | "dark" | "auto" are accepted and treated as `mode`.
   */
  theme?: string | ThemeDef | ResolvedTheme;
  /** Token overrides: `{ accent: "#6b7a2f", dark: { accent: "#a9bb62" }, tones: { data: "#c8d8c4" } }`. */
  palette?: Palette;
  /** Below this width the figure scrolls horizontally instead of shrinking the text. */
  minWidth?: number;
  className?: string;
}

const STYLE = `
.dgm-fig{margin:2rem 0}
.dgm-fig .dgm-scroll{overflow-x:auto}
.dgm-fig svg.dgm{display:block;width:100%;height:auto;min-width:var(--dgm-min,640px)}
.dgm-fig figcaption{font-family:Georgia,'Source Serif 4',serif;font-size:.85rem;color:#777;margin-top:.5rem}
`;

function siteMode(): "light" | "dark" | undefined {
  const el = document.documentElement;
  const t = el.getAttribute("data-theme") ?? el.getAttribute("data-mode");
  if (t === "dark" || t === "light") return t;
  if (el.classList.contains("dark")) return "dark";
  if (el.classList.contains("light")) return "light";
  return undefined;
}

export function Diagram({ svg, caption, mode, theme, palette, minWidth = 640, className }: DiagramProps) {
  const host = useRef<HTMLDivElement>(null);

  // legacy: theme="dark" means mode
  let effMode: Mode = mode ?? "auto";
  let effTheme = theme;
  if (typeof theme === "string" && isMode(theme)) {
    if (!mode) effMode = theme;
    effTheme = undefined;
  }

  const vars = useMemo(() => {
    if (!effTheme && !palette) return undefined;
    const base: ResolvedTheme = effTheme
      ? resolveTheme(effTheme)
      : { resolved: true, name: "", light: {}, dark: {}, fonts: {} };
    return themeToCssVars(applyPalette(base, palette));
  }, [effTheme, palette]);

  useEffect(() => {
    const el = host.current?.querySelector<SVGSVGElement>("svg.dgm");
    if (!el) return;
    attach(el);
    const sync = () => {
      const m = effMode === "auto" ? siteMode() : effMode;
      if (m) el.setAttribute("data-mode", m);
      else el.removeAttribute("data-mode");
    };
    sync();
    if (effMode !== "auto") return;
    const mo = new MutationObserver(sync);
    mo.observe(document.documentElement, { attributes: true, attributeFilter: ["class", "data-theme", "data-mode"] });
    return () => mo.disconnect();
  }, [svg, effMode]);

  return (
    <figure
      className={`dgm-fig ${className ?? ""}`}
      style={{ ["--dgm-min" as any]: `${minWidth}px`, ...(vars as any) }}
    >
      <style dangerouslySetInnerHTML={{ __html: STYLE }} />
      {/* SVG is generated by our own renderer from a validated spec; labels are escaped. */}
      <div className="dgm-scroll" ref={host} dangerouslySetInnerHTML={{ __html: svg }} />
      {caption && <figcaption>{caption}</figcaption>}
    </figure>
  );
}

export default Diagram;
